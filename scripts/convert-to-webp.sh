#!/usr/bin/env bash
# Converts every PNG under assets/screenshots to a same-name .webp beside it,
# keeping the originals. Regenerates assets/css/screenshots.css with each
# image's aspect ratio (used to prevent layout shift without hardcoding
# dimensions in the markup). Safe to re-run: up-to-date outputs are skipped.
#
# Needs ImageMagick (magick).
set -euo pipefail

cd "$(dirname "$0")/../assets/screenshots"

convert_image() {
    magick "$1" -quality 85 "$2"
}

total_before=0
total_after=0
ratios=""

for src in light/*.png dark/*.png; do
    [ -e "$src" ] || continue
    out="${src%.png}.webp"

    # Re-convert only when the PNG is newer than its .webp
    if [ ! -f "$out" ] || [ "$src" -nt "$out" ]; then
        convert_image "$src" "$out"
    fi

    # PNG IHDR: width and height are big-endian u32 values at byte offset 16
    dims=$(od -An -tx1 -j16 -N8 "$src" | tr -d ' \n')
    width=$((16#${dims:0:8}))
    height=$((16#${dims:8:8}))
    name="${src#*/}"
    name="${name%.png}"
    ratios="${ratios}img[src\$=\"/${name}.png\"], img[src\$=\"/${name}.webp\"] { aspect-ratio: ${width} / ${height}; }
"

    before=$(wc -c < "$src")
    after=$(wc -c < "$out")
    total_before=$((total_before + before))
    total_after=$((total_after + after))
done

# Aspect-ratio styles for index.html's `css: [..., screenshots]`
{
    echo "/* Generated by scripts/convert-to-webp.sh - do not edit by hand. */"
    printf '%s' "$ratios"
} > ../css/screenshots.css

awk "BEGIN { printf \"done: %.1f KiB -> %.1f KiB (%.0f%% smaller)\\n\", $total_before / 1024, $total_after / 1024, (1 - $total_after / $total_before) * 100 }"
